import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
const root=resolve('.build/public'),html=await readFile(root+'/index.html','utf8');
const report=JSON.parse(await readFile('.build/report.json','utf8'));
const styles=[...html.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"/g)].map(m=>m[1]);
const scripts=[...html.matchAll(/<script[^>]+src="([^"]+)"/g)].map(m=>m[1]);
assert.equal(styles.length,1);assert.equal(scripts.length,1);
assert(!/(?:href|src)="https?:\/\//.test(html),'critical resources must be same-origin');
assert(report.script.brotliBytes<200000,'compressed entry exceeds budget');
assert(report.style.brotliBytes<40000,'compressed styles exceed budget');
assert(report.fontCoreBytes<300000,'first-view fonts exceed budget');
for(const href of [...styles,...scripts])await access(resolve(root,href));
const path=resolve(root,styles[0]),css=await readFile(path,'utf8');
assert(!/font-display:\s*block/.test(css));
assert(!/url\(["']?https?:\/\//.test(css),'font requests must not use external CDNs');
for(const match of css.matchAll(/url\(["']?([^)'"\s]+)["']?\)/g))await access(resolve(dirname(path),match[1]));
const headers=await readFile(root+'/_headers','utf8');assert.match(headers,/max-age=31536000, immutable/);assert(!headers.includes('/api/'));
console.log('生产资源检查通过：单个脚本、单个样式、字体同源、压缩体积及缓存规则符合预算。');
